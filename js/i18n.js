let currentLang = 'id';

function setLanguage(lang) {
  if (!i18n[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;

  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.dataset.i18n;
    if (i18n[lang][key]) {
      el.textContent = i18n[lang][key];
    }
  });

  const ariaElements = document.querySelectorAll('[data-i18n-aria]');
  ariaElements.forEach(el => {
    const key = el.dataset.i18nAria;
    if (i18n[lang][key]) {
      el.setAttribute('aria-label', i18n[lang][key]);
    }
  });

  const dialogElements = document.querySelectorAll('[data-i18n-dialog]');
  dialogElements.forEach(el => {
    const key = el.dataset.i18nDialog;
    if (i18n[lang][key]) {
      el.setAttribute('aria-label', i18n[lang][key]);
    }
  });
}

function t(key) {
  return i18n[currentLang][key] || i18n['id'][key] || key;
}

function detectLanguage() {
  const lang = navigator.language || navigator.userLanguage || 'id';
  return lang.startsWith('id') ? 'id' : 'en';
}
